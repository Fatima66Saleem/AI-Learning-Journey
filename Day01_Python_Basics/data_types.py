
# type() function is used to check the data type of a variable

# String - text/characters
name = "Fatima Saleem"
print(type(name))    # <class 'str'>

# Integer - a whole number (no decimal)
marks = 90
print(type(marks))   # <class 'int'>

# Float - a decimal number
PI = 3.14
print(type(PI), PI)  # <class 'float'> 3.14

# Boolean - can only be True or False
number = 6
isprime = False
print(type(isprime))   # <class 'bool'>

# NoneType - represents "no value" / empty / undefined
number = None
print(type(number))    # <class 'NoneType'>