print("Hello World") #print is a function of python
print("My name is: \nFatima") #\n is for new line

# To make quotes appear literally in the output,
# wrap the string in single quotes and use double quotes inside
print('"Hello"')

# Alternative: use backslash to escape the double quotes
print("\"Hello\"")

print("")  #empty string

print("Name:\tFatima")  # \t = tab space


# \b is the backspace escape sequence
# it moves the cursor one step back (like pressing Backspace)
# not commonly used, but useful to recognize
print("Fatima\b")

# common escape sequences for reference:
print("Line1\nLine2")     # \n = new line
print("Name:\tFatima")    # \t = tab space
print("She said \"Hi\"")  # \" = double quote inside string
print('It\'s mine')       # \' = single quote inside string
print("C:\\Users\\Fatima") # \\ = single backslash

